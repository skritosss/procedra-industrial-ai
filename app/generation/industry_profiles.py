def profile_label(profile: str) -> str:
    return PROFILE_LABELS.get(profile, PROFILE_LABELS["general"])


def profile_guardrails(profile: str) -> list[str]:
    return PROFILE_GUARDRAILS.get(profile, PROFILE_GUARDRAILS["general"])


def render_profile_context(profile: str) -> str:
    guardrails = profile_guardrails(profile)
    return "\n".join(
        [
            f"Отраслевой профиль: {profile_label(profile)}.",
            "Профильные требования:",
            *(f"- {item}" for item in guardrails),
        ]
    )
