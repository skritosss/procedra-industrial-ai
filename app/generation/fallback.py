def _context_bullets(context: str | None) -> list[str]:
    if not context:
        return []
    cleaned = re.sub(r"\[[^\]]+\]", " ", context)
    cleaned = cleaned.replace("Найденные фрагменты технической документации:", "\n")
    sentences = [
        sentence.strip(" -\n\t")
        for sentence in re.split(r"(?<=[.!?])\s+|\n+", cleaned)
        if sentence.strip(" -\n\t")
    ]
    useful = []
    seen = set()
    for sentence in sentences:
        compact = re.sub(r"\s+", " ", sentence)
        if _is_context_heading_or_metadata(compact):
            continue
        if len(compact) < 35:
            continue
        key = compact.lower()
        if key in seen:
            continue
        seen.add(key)
        useful.append(compact[:220])
        if len(useful) >= 3:
            break
    return useful


def _is_context_heading_or_metadata(sentence: str) -> bool:
    lowered = sentence.lower().strip(" .:")
    metadata_prefixes = (
        "отраслевой профиль",
        "профильные требования",
        "найденные фрагменты",
        "контекст автоматически сокращен",
        "контекст видео автоматически сокращен",
    )
    return lowered.startswith(metadata_prefixes)


def _single_line(value: str) -> str:
    return re.sub(r"\s+", " ", value).strip()


def _truncate_title(value: str, limit: int = 90) -> str:
    compact = _single_line(value)
    if len(compact) <= limit:
        return compact
    truncated = compact[: limit + 1].rsplit(" ", 1)[0].strip(" ,.;:")
    return f"{truncated}..."


def _observed_facts(
    request: InstructionRequest,
    context_bullets: list[str],
    instruction_type: str,
) -> list[str]:
    facts = [
        f"Тип инструкции: {instruction_type}.",
        f"Уровень пользователя: {USER_LEVEL_LABELS[request.user_level]}.",
        f"Отраслевой профиль: {profile_label(request.industry_profile)}.",
    ]
    if request.department:
        facts.append(f"Участок указан во входных данных: {request.department}.")
    if request.equipment:
        facts.append(f"Оборудование указано во входных данных: {request.equipment}.")
    if request.operation_name:
        facts.append(f"Название операции указано во входных данных: {request.operation_name}.")
    facts.extend(f"Непроверенное утверждение из входного контекста: {item}" for item in context_bullets[:3])
    return facts[:8]


