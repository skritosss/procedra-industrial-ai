def _workflow(request: InstructionRequest, local_verification: list[str]) -> InstructionWorkflow:
    roles = [
        "Мастер смены или руководитель участка",
        "Инженер/технолог",
        "Специалист по охране труда",
    ]
    if request.industry_profile in {"construction", "emergency_response", "occupational_safety"}:
        roles.append("Ответственный за безопасное производство работ")
    if request.industry_profile in {"healthcare", "food_production"}:
        roles.append("Ответственный за санитарные требования и качество")

    blockers = [
        "Инструкция является AI-черновиком и не имеет статуса утвержденного документа предприятия.",
        *local_verification[:5],
    ]
    next_actions = [
        "Передать инструкцию на проверку ответственным ролям из матрицы согласования.",
        "Заполнить неподтвержденные параметры, ссылки на локальные документы и критерии приемки.",
        "Провести пробное применение на безопасном учебном или контролируемом участке.",
        "После замечаний зафиксировать утвержденную версию и дату следующего пересмотра.",
    ]
    return InstructionWorkflow(
        status="ai_draft",
        status_label="AI-черновик",
        required_review_roles=_deduplicate(roles),
        approval_blockers=_deduplicate(blockers),
        next_actions=next_actions,
    )


def _deduplicate(items: list[str]) -> list[str]:
    result = []
    seen = set()
    for item in items:
        key = item.lower()
        if key in seen:
            continue
        seen.add(key)
        result.append(item)
    return result


def _control_points_from_steps(steps: list[InstructionStep]) -> list[str]:
    """Turn the first steps into control points that name the work.

    A control point that does not refer to any step cannot be used to check the
    work: "PPE and documentation prepared" is true of every procedure ever
    written. These name what this instruction actually asks for, which is what
    makes the list checkable on the floor.
    """
    points: list[str] = []
    for step in steps[:3]:
        action = step.action.rstrip(". ")
        if len(action) > 90:
            action = action[:90].rsplit(" ", 1)[0]
        points.append(f"Шаг {step.number} выполнен и подтвержден: {action}.")
    return points


def _steps_for_type(
    request: InstructionRequest,
    operation: str,
    equipment: str,
    context_bullets: list[str],
) -> list[InstructionStep]:
    context_reference = (
        f"Отдельно сверить требование: {context_bullets[0]}"
        if context_bullets
        else "Отдельно сверить локальные режимы, допуски и ограничения по документации участка."
    )
    builders = {
        "workplace_preparation": _workplace_preparation_steps,
        "equipment_startup": _equipment_startup_steps,
        "equipment_shutdown": _equipment_shutdown_steps,
        "inspection": _inspection_steps,
        "training": _training_steps,
        "maintenance": _maintenance_steps,
        "general": _general_steps,
    }
    return builders[request.instruction_type](operation, equipment, context_reference)


