"""Industry-specific content the draft gains on top of its operation template.

The steps of a procedure follow its type — prepare, start, inspect, shut down —
and that structure is the same in a workshop and in a manhole. What differs is
the concrete part: which hazards exist, what has to be checked before the work
starts, what protects the person doing it. Until this module existed the profile
changed a label and two sentences, so a utilities draft and a metalworking draft
read almost identically.

Two rules keep this from becoming a way to inflate scores.

First, a block is added only when the work actually calls for it. A utilities
request about a manhole gets confined-space requirements; a request about
changing a lamp in a stairwell does not. Attaching everything to everyone would
bury the reader and make the section noise.

Second, the text is written as an instruction to a person, not as a bag of the
words the evaluator looks for. The regulatory checks search for the trace of a
subject; if these blocks were assembled out of those markers, the checks would
pass while measuring nothing. The wording here comes from published requirements
for each kind of work, named in `source`.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class ProfileStep:
    action: str
    expected_result: str
    safety_note: str
    verification_method: str
    common_mistakes: tuple[str, ...]


@dataclass(frozen=True)
class ProfileSpecifics:
    profile: str
    name: str
    source: str
    # Words that must appear in the task, operation or context for the block to
    # apply. Empty means the block applies to every request of the profile.
    triggers: tuple[str, ...] = ()
    instruction_types: tuple[str, ...] = ()
    steps: tuple[ProfileStep, ...] = ()
    safety_requirements: tuple[str, ...] = ()
    hazard_zones: tuple[str, ...] = ()
    required_ppe: tuple[str, ...] = ()
    emergency_actions: tuple[str, ...] = ()
    expert_questions: tuple[str, ...] = field(default_factory=tuple)
    local_verification: tuple[str, ...] = field(default_factory=tuple)

    def applies(self, profile: str, instruction_type: str, request_text: str) -> bool:
        if profile != self.profile:
            return False
        if self.instruction_types and instruction_type not in self.instruction_types:
            return False
        if not self.triggers:
            return True
        lowered = request_text.casefold()
        return any(trigger in lowered for trigger in self.triggers)


